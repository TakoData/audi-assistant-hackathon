// Bundle a pinned map renderer locally; only visible street tiles need a network.
import { readFileSync, writeFileSync } from 'node:fs';
const root = new URL('../', import.meta.url);
const js = readFileSync(new URL('node_modules/leaflet/dist/leaflet.js', root), 'utf8');
const css = readFileSync(new URL('node_modules/leaflet/dist/leaflet.css', root), 'utf8');
const license = readFileSync(new URL('node_modules/leaflet/LICENSE', root), 'utf8');
writeFileSync(new URL('src/mapAssets.ts', root), '// Generated by scripts/prepare-map.mjs. Leaflet 1.9.4.\n/*\n' + license + '\n*/\nexport const mapScript = ' + JSON.stringify(js) + ';\nexport const mapStyle = ' + JSON.stringify(css) + ';\n');
